/**
 * Retrieves the typed CityConfig for a given city slug, with support for aliases.
 */
export function getCityConfig(slug: string): CityConfig | null {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim();

  if (TOP_CITIES[normalized]) {
    return TOP_CITIES[normalized];
  }

  // Handle common aliases and redirect keys
  const aliasMap: Record<string, string> = {
    kashi: 'varanasi',
    banaras: 'varanasi',
    allahabad: 'prayagraj',
    bangalore: 'bengaluru',
    calcutta: 'kolkata',
    madras: 'chennai',
    bombay: 'mumbai',
    gurgaon: 'delhi',
    gurugram: 'delhi',
  };

  const targetSlug = aliasMap[normalized];
  if (targetSlug && TOP_CITIES[targetSlug]) {
    return TOP_CITIES[targetSlug];
  }

  return null;
}

